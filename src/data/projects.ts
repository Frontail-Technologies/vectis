export const featuredProjects: ProjectItem[] = allProjects.slice(0, 6);

export function getAllProjects(): ProjectItem[] {
  return allProjects;
}

export function getProjectBySlug(slug: string): ProjectItem | undefined {
  return allProjects.find((p) => p.id === slug);
}

export function getRelatedProjects(slug: string, limit = 3): ProjectItem[] {
  const current = getProjectBySlug(slug);
  if (!current) return allProjects.slice(0, limit);

  if (current.relatedProjectSlugs && current.relatedProjectSlugs.length > 0) {
    const related = current.relatedProjectSlugs
      .map((id) => allProjects.find((p) => p.id === id))
      .filter((p): p is ProjectItem => !!p);
    if (related.length > 0) return related.slice(0, limit);
  }

  return allProjects.filter((p) => p.id !== slug).slice(0, limit);
}
